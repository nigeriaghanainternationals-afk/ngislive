-- NGIS: Parent notifications setup. Run ONCE in Supabase > SQL Editor.

-- 1) Parent contact details on each student
alter table public.students add column if not exists parent_name  text;
alter table public.students add column if not exists parent_phone text;
alter table public.students add column if not exists parent_email text;

-- 2) Notice board (shown on parent, teacher and admin dashboards)
create table if not exists public.announcements(
  id bigint generated by default as identity primary key,
  title text,
  body text not null,
  audience text not null default 'parents',   -- parents | staff | all
  class_id text,                              -- null = every class
  created_by text,
  created_by_name text,
  expires_at date,
  created_at timestamptz default now()
);

-- 3) History of every alert (also the queue for automatic sending)
create table if not exists public.notification_log(
  id bigint generated by default as identity primary key,
  kind text,                 -- absent | results | fees | notice
  channel text,              -- whatsapp | sms | email
  student_id text,
  recipient text,
  subject text,
  message text,
  status text default 'queued',   -- queued | opened | sent | failed
  error text,
  created_by text,
  created_at timestamptz default now(),
  sent_at timestamptz
);

alter table public.announcements    enable row level security;
alter table public.notification_log enable row level security;
drop policy if exists "ann_all" on public.announcements;
drop policy if exists "ntf_all" on public.notification_log;
-- Same access style as the rest of the app (it signs in inside the browser with the public key).
create policy "ann_all" on public.announcements    for all using (true) with check (true);
create policy "ntf_all" on public.notification_log for all using (true) with check (true);

notify pgrst, 'reload schema';
