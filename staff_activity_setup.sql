-- NGIS: Staff Activity (login / logout history). Run ONCE in Supabase > SQL Editor.
create table if not exists public.staff_sessions(
  id bigint generated by default as identity primary key,
  session_key text not null unique,
  user_uid text not null,            -- e.g. teacher:12 / admin:1 / management:3
  name text,
  role text,                         -- teacher | admin | management
  position text,
  sections text,                     -- e.g. "Primary, Nursery"
  login_at timestamptz not null default now(),
  last_seen timestamptz not null default now(),
  logout_at timestamptz,
  last_page text,
  device text
);
create index if not exists staff_sessions_login_idx on public.staff_sessions (login_at desc);
alter table public.staff_sessions enable row level security;
drop policy if exists "ss_all" on public.staff_sessions;
create policy "ss_all" on public.staff_sessions for all using (true) with check (true);
notify pgrst, 'reload schema';
