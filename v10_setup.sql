-- NGIS v10 setup. Run ONCE in Supabase > SQL Editor (after notifications_setup.sql).

-- 1) Report-card link on each queued message
alter table public.notification_log add column if not exists attachment_url text;

-- 2) Storage bucket that holds the report-card PDFs sent to parents.
--    Public bucket: parents open the link without logging in. Each file sits under a random
--    32-character folder name, so a link cannot be guessed. The app can add files but
--    nobody can list or browse the bucket.
insert into storage.buckets (id, name, public)
values ('report-cards', 'report-cards', true)
on conflict (id) do update set public = true;

drop policy if exists "rc_upload" on storage.objects;
create policy "rc_upload" on storage.objects
  for insert to anon, authenticated
  with check (bucket_id = 'report-cards');

-- 3) CBT categories: weekly | exam | jamb (these columns may already exist; safe to re-run)
alter table public.quizzes add column if not exists quiz_type  text default 'weekly';
alter table public.quizzes add column if not exists term_id    text;
alter table public.quizzes add column if not exists session_id text;

-- 4) Saved Incident & Concern reports and Lesson Observation sheets
create table if not exists public.form_submissions(
  id bigint generated by default as identity primary key,
  kind text not null,                 -- incident | observation
  title text,
  data jsonb not null,
  submitted_by text,
  submitted_by_name text,
  submitted_by_role text,
  created_at timestamptz default now(),
  updated_at timestamptz
);
alter table public.form_submissions enable row level security;
drop policy if exists "fs_all" on public.form_submissions;
create policy "fs_all" on public.form_submissions for all using (true) with check (true);

notify pgrst, 'reload schema';
